import { build } from 'esbuild'
import { writeFile, readFile } from 'node:fs/promises'

// Derive the module id from package.json so a rename cannot desync the built
// bundle from the manifest.
const pkg = JSON.parse(await readFile('package.json', 'utf8'))

const result = await build({
  entryPoints: ['src/client.js'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'chrome120',
  write: false,
  external: ['react'],
  minify: false,
})

// esbuild emits the platform's line ending, so a Windows build writes CRLF while
// a Linux one writes LF. The bundle is committed, so normalize to LF and a clean
// checkout can prove it by rebuilding to an identical hash.
const body = result.outputFiles[0].text.replace(/\r\n/g, '\n')

await writeFile(
  'client.js',
  `// Generated by npm run build.\nwindow.__ModuleLoader__.load({id:'${pkg.name}',factory(require){\nvar module={exports:{}},exports=module.exports;\n${body}\nreturn module.exports;\n}});\n`,
)
